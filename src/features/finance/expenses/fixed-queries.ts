import "server-only";

import type { Types } from "mongoose";
import { connectDB } from "@/server/db";
import { FixedAsset } from "@/server/models";
import type { ListParams, Paginated } from "@/lib/list-params";
import { listExpenses } from "./queries";
import type { ExpenseRow, ExpenseSummary } from "./types";

/**
 * Fixed payments (/finance/expenses/fixed): one-off purchases of goods, the things not bought every
 * month. What is paid on a cycle (rent, bills, loan EMIs) is under Recurring expenses instead.
 *
 * A purchase here is an expense not posted by a recurring schedule that is in a goods category
 * (materials, equipment, inventory), is a stock purchase, or paid for a fixed asset. Rows that
 * other records generate are left out: stock assignments and wastage, stock counted at purchase on
 * a project, and loan interest. The list, its filters and its totals are the Total expenses list's
 * own (listExpenses), so paid and outstanding read exactly as they do there.
 */

/** Expense categories that are goods bought, not services or running costs. */
export const GOODS_CATEGORIES: readonly string[] = ["materials", "equipment", "inventory"];

/** Sources that never count as a purchase here: posted by a schedule, or generated by another record. */
const NOT_PURCHASES = ["recurring", "inventory_assignment", "inventory_wastage", "liability_interest"];

/**
 * The Mongo condition for one-off purchases of goods. Older asset purchases link the expense only
 * from the asset (`funding.expense`), so those expense ids are read from the register.
 */
export async function oneOffPurchasesFilter(): Promise<Record<string, unknown>> {
  await connectDB();
  const funded = (await FixedAsset.distinct("funding.expense", { "funding.expense": { $type: "objectId" } })) as Types.ObjectId[];
  return {
    source: { $nin: NOT_PURCHASES },
    countedAtPurchase: { $ne: true },
    $or: [
      { category: { $in: [...GOODS_CATEGORIES] } },
      { source: "inventory_purchase" },
      { capitalAsset: { $type: "objectId" } },
      ...(funded.length ? [{ _id: { $in: funded } }] : []),
    ],
  };
}

/** The purchases for the page: rows, count and header figures (total, paid, outstanding) with the list's filters and salary scope. */
export async function listOneOffPurchases(params: ListParams): Promise<Paginated<ExpenseRow> & { summary: ExpenseSummary }> {
  return listExpenses(params, { where: await oneOffPurchasesFilter() });
}
