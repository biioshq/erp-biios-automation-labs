import { Schema, model, models, type InferSchemaType, type Model, type Types } from "mongoose";
import {
  DEPARTMENTS,
  EXPENSE_SOURCES,
  PAYMENT_METHODS,
  PROJECT_STAGES,
  valuesOf,
} from "@/lib/constants";

/**
 * A payment made against an expense. An expense without `payments` is settled the old way: paid in
 * full on its date unless its method is "On credit" (then unpaid). With `payments`, those are what
 * was paid (src/lib/payments.ts). Additive: existing expenses never get this field written.
 */
const expensePaymentSchema = new Schema(
  {
    date: { type: Date, required: true },
    amount: { type: Number, required: true, min: 0 },
    paymentMethod: { type: String, enum: valuesOf(PAYMENT_METHODS), required: true },
    account: { type: Schema.Types.ObjectId, ref: "BankAccount" },
    reference: { type: String, trim: true, maxlength: 120 },
    note: { type: String, trim: true, maxlength: 1000 },
    bankTransaction: { type: Schema.Types.ObjectId, ref: "BankTransaction" },
    createdBy: { type: Schema.Types.ObjectId, ref: "User" },
  },
  { timestamps: true },
);

/** GST invoice details. All optional: not every expense has a tax invoice. */
const gstSchema = new Schema(
  {
    gstin: { type: String, uppercase: true, trim: true },
    invoiceNumber: { type: String, trim: true },
    invoiceDate: { type: Date },
    taxableAmount: { type: Number, min: 0, default: 0 },
    cgst: { type: Number, min: 0, default: 0 },
    sgst: { type: Number, min: 0, default: 0 },
    igst: { type: Number, min: 0, default: 0 },
    cess: { type: Number, min: 0, default: 0 },
    hsnSac: { type: String, trim: true },
    grandTotal: { type: Number, min: 0, default: 0 },
  },
  { _id: false },
);

const expenseSchema = new Schema(
  {
    /** EXP-2026-00042 */
    number: { type: String, required: true, unique: true },
    vendor: { type: String, required: true, trim: true, maxlength: 200 },
    vendorAddress: { type: String, trim: true, maxlength: 500 },
    project: { type: Schema.Types.ObjectId, ref: "Project", index: true },
    /** Every project expense belongs to exactly one stage. */
    stage: { type: String, enum: valuesOf(PROJECT_STAGES) },
    /** A built-in value (EXPENSE_CATEGORIES) or a custom one (expenseCategories). The actions check it, not an enum, so custom values save. */
    category: { type: String, required: true, index: true },
    description: { type: String, trim: true, maxlength: 1000 },
    /** The amount paid, GST included (equals gst.grandTotal when GST is recorded). */
    amount: { type: Number, required: true, min: 0 },
    date: { type: Date, required: true, index: true },
    paymentMethod: { type: String, enum: valuesOf(PAYMENT_METHODS), required: true },
    notes: { type: String, trim: true, maxlength: 4000 },
    gst: { type: gstSchema, default: undefined },
    receipt: { type: Schema.Types.ObjectId, ref: "File" },
    /** Confidence (0–1) per OCR field when the expense was filled from a receipt. */
    ocr: {
      type: new Schema(
        { overall: Number, source: String, fields: { type: Map, of: Number } },
        { _id: false },
      ),
      default: undefined,
    },
    /**
     * manual, or generated by inventory (then edited only through inventory): "inventory_purchase" when
     * stock is bought, "inventory_assignment" when stock is assigned to a project.
     */
    source: { type: String, enum: valuesOf(EXPENSE_SOURCES), default: "manual", index: true },
    /**
     * True on an assignment record for stock that was already expensed when it was bought. It counts in
     * the project's spend, budget and stage totals, but never in company totals (dashboard, Expenses list
     * totals, finance, expense, GST and CA reports), or the purchase would be counted twice. Missing on
     * every older record, which therefore counts everywhere as before. Filter with `{ $ne: true }`.
     */
    countedAtPurchase: { type: Boolean },
    item: { type: Schema.Types.ObjectId, ref: "InventoryItem" },
    allocation: { type: Schema.Types.ObjectId, ref: "InventoryAllocation" },
    /** The stock purchase movement behind an "inventory_purchase" expense. */
    movement: { type: Schema.Types.ObjectId, ref: "InventoryMovement" },
    /** Posted by a recurring schedule. */
    recurring: { type: Schema.Types.ObjectId, ref: "RecurringExpense", index: true },
    /** "<schedule id>:<yyyy-mm-dd>": unique, so an occurrence is never posted twice. */
    occurrenceKey: { type: String },
    /** Whose salary this is, for salary expenses. */
    employee: { type: Schema.Types.ObjectId, ref: "Employee", index: true },
    quantity: { type: Number },
    unitCost: { type: Number },
    /** When an unpaid or part-paid bill falls due. */
    dueDate: { type: Date },
    /** Payments against it; missing on every older expense (see expensePaymentSchema). */
    payments: { type: [expensePaymentSchema], default: undefined },
    /** The bank or cash account it was paid from, when paid on its date; missing = the default for its method. */
    account: { type: Schema.Types.ObjectId, ref: "BankAccount" },
    department: { type: String, enum: valuesOf(DEPARTMENTS) },
    /** Paid in advance for a period (insurance, an annual licence): the cost is spread over these days. */
    prepaid: {
      type: new Schema({ from: { type: Date, required: true }, to: { type: Date, required: true } }, { _id: false }),
      default: undefined,
    },
    /** The fixed asset this expense paid for: its cost is the asset's, not a running expense. */
    capitalAsset: { type: Schema.Types.ObjectId, ref: "FixedAsset" },
    /** Interest on this loan (source "liability_interest"). */
    liability: { type: Schema.Types.ObjectId, ref: "Liability" },
    /** The bank statement line it came from or was matched to. */
    bankTransaction: { type: Schema.Types.ObjectId, ref: "BankTransaction" },
    createdBy: { type: Schema.Types.ObjectId, ref: "User" },
  },
  { timestamps: true },
);
expenseSchema.index({ project: 1, date: -1 });
expenseSchema.index({ dueDate: 1 }, { partialFilterExpression: { dueDate: { $type: "date" } } });
expenseSchema.index({ project: 1, stage: 1 });
expenseSchema.index({ vendor: 1 });
expenseSchema.index({ occurrenceKey: 1 }, { unique: true, partialFilterExpression: { occurrenceKey: { $type: "string" } } });
expenseSchema.index({ "gst.gstin": 1 });
expenseSchema.index({ vendor: "text", description: "text", number: "text", "gst.invoiceNumber": "text", notes: "text" });

export type ExpenseDoc = InferSchemaType<typeof expenseSchema> & { _id: Types.ObjectId };
export const Expense: Model<ExpenseDoc> = models.Expense ?? model<ExpenseDoc>("Expense", expenseSchema, "expenses");
